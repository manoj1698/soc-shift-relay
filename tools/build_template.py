"""Build switch/soc-shift-relay.template.yaml from the source files.

Sources of truth:
  workspaces/<agent>/AGENT.md   agent briefs
  switch/room-soc-shift.md      #soc-shift room instructions
  switch/room-security-help.md  #security-help room instructions
  switch/roles.md               roles (level-2 heading = role name, then "exclusive: true|false", then text)
  switch/runbook.md             runbook, created as a room document in #soc-shift

The template uses the Switch template language version 1 (a group with two rooms and a link).
Run after editing any source. `--check` exits 1 if the committed template is out of date.
Standard library only, so no YAML library is needed: every text field is written as a literal block.
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "switch" / "soc-shift-relay.template.yaml"

AGENTS = [
    # (workspace folder, name suffix, description, addressing, auto_mode)
    ("triage", "triage", "Triages every alert and employee report against the runbook", "anyone", True),
    ("responder", "responder", "Prepares containment and runs it only after on-call approval", "owner-agents", False),
    ("scribe", "scribe", "Keeps the shift-log room document and briefs each new shift", "anyone", True),
    ("appsec", "appsec", "Scans every code push for secrets, risky code, vulnerable dependencies and malware; prepares fixes",
     "owner-agents", True),
    ("alert-sim", "siem", "The SOC's alerting system (SIEM): posts each security alert and code push to #soc-shift",
     "owner", True),
]

PLACEHOLDER = re.compile(r"\{[A-Za-z_$][A-Za-z0-9_]*\}")


def read(rel: str) -> str:
    text = (ROOT / rel).read_text(encoding="utf-8").replace("\r\n", "\n").strip() + "\n"
    bad = PLACEHOLDER.findall(text)
    if bad:
        sys.exit(f"{rel}: remove template-style braces {sorted(set(bad))}; Switch would treat them as placeholders")
    if "\t" in text:
        sys.exit(f"{rel}: contains a tab character; use spaces")
    return text


def block(text: str, indent: int) -> str:
    pad = " " * indent
    return "|\n" + "".join((pad + line) if line else "" for line in text.splitlines(True))


def q(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def parse_roles(text: str):
    roles = []
    for chunk in text.split("\n## ")[1:]:
        lines = chunk.strip().splitlines()
        name = lines[0].strip()
        m = re.match(r"exclusive:\s*(true|false)\s*$", lines[1].strip())
        if not m:
            sys.exit(f"roles.md: role {name!r} needs an 'exclusive: true|false' line under its heading")
        body = "\n".join(lines[2:]).strip() + "\n"
        roles.append((name, m.group(1), body))
    if not roles:
        sys.exit("roles.md: no roles found")
    return roles


def build() -> str:
    out = []
    w = out.append
    w("# SOC Shift Relay: a security operations room for shift teams, built on Switch.\n")
    w("#\n")
    w("# GENERATED by tools/build_template.py from workspaces/*/AGENT.md and switch/*.md. Do not edit by hand.\n")
    w("# Import it in Switch Console: Templates > Import template, then Use.\n")
    w("# Creates five agents (Switch Console runs them on this computer), a group with two rooms\n")
    w("# (#soc-shift and #security-help) linked together, the four roles, the runbook document,\n")
    w("# and kickoff messages that ask each agent to take its role.\n")
    w("# Every agent runs on Claude Code, because its permission rules are Claude Code settings.\n")
    w("version: 1\n\n")
    w("params:\n")
    w("  team:\n")
    w("    type: string\n")
    w("    label: Name prefix\n")
    w("    description: Prefix for every agent name, for example soc gives soc-triage\n")
    w('    pattern: "[a-z][a-z0-9-]*"\n')
    w("    default: soc\n")
    w("  project_dir:\n")
    w("    type: string\n")
    w("    label: Project folder\n")
    w("    description: Where you cloned this repo, with forward slashes. Each agent works in its folder under workspaces/.\n")
    w('    default: "D:/Manoj/soc-shift-relay"\n')
    w("  bridge:\n")
    w("    type: bridge\n")
    w("    description: The messaging app connection the rooms are created on (your Discord server)\n")
    w("    default: [$first]\n")
    w("  location:\n")
    w("    type: location\n")
    w("    description: The machine the agents run on\n")
    w("    default: local\n")
    w("    input: advanced\n\n")

    w("agents:\n")
    for folder, suffix, desc, addressing, auto in AGENTS:
        brief = read(f"workspaces/{folder}/AGENT.md")
        w(f'  - name: "{{team}}-{suffix}"\n')
        w(f"    description: {q(desc)}\n")
        w(f"    addressing: {addressing}\n")
        w(f"    auto_mode: {'true' if auto else 'false'}\n")
        w("    auto_approve: false\n")
        # Pinned, not a param: the agents' guardrails are Claude Code settings (agent-settings.json), and Switch
        # Console on Windows cannot fill a provider param (its picker needs a POSIX SSH host for SDK sessions).
        w("    provider: claude\n")
        w('    location: "{location}"\n')
        w(f'    directory: "{{project_dir}}/workspaces/{folder}"\n')
        w("    instructions: " + block(brief, 6))
    w("\n")

    w("group:\n")
    w('  name: "{team} shift relay"\n')
    w("  description: SOC desk and the employee help room, with agents that keep watch between shifts\n\n")
    w("rooms:\n")
    # SOC desk
    w('  - name: "soc-shift"\n')
    w("    description: SOC desk where agents triage, contain with approval, and keep the shift log\n")
    w('    bridge: "{bridge}"\n')
    w("    instructions: " + block(read("switch/room-soc-shift.md"), 6))
    w('    agents: ["{team}-triage", "{team}-responder", "{team}-scribe", "{team}-appsec", "{team}-siem"]\n')
    w('    users: ["{$creator}"]\n')
    w("    roles:\n")
    for name, exclusive, body in parse_roles(read("switch/roles.md")):
        w(f"      - name: {name}\n")
        w(f"        exclusive: {exclusive}\n")
        w("        instructions: " + block(body, 10))
    w("    docs:\n")
    w("      - name: runbook\n")
    w("        description: The SOC runbook - tiers, severities, playbooks and protected targets\n")
    w("        instructions: Read before your first decision in this room. Its tiers decide what an agent may do alone, what needs on-call approval, and what only people do. Only people change it.\n")
    w("        content: " + block(read("switch/runbook.md"), 10))
    w("    kickoff: |\n")
    for line in [
        "@{team}-triage @{team}-responder @{team}-scribe @{team}-appsec @{team}-siem welcome to the SOC desk.",
        "Read the room instructions and the runbook document first, then:",
        "- @{team}-triage: take the triage job.",
        "- @{team}-responder: take the responder job.",
        "- @{team}-scribe: take the scribe job and create the shift-log and on-call-roster room documents from your brief.",
        "- @{team}-appsec: take the appsec job.",
        "- @{team}-siem: wait for my \"start night shift\".",
        "Each of you, confirm in one line which job you hold.",
    ]:
        w("      " + line + "\n")
    # Employee help room
    w('  - name: "security-help"\n')
    w("    description: Employees report security problems here at any hour; triage answers\n")
    w('    bridge: "{bridge}"\n')
    w("    instructions: " + block(read("switch/room-security-help.md"), 6))
    w('    agents: ["{team}-triage"]\n')
    w('    users: ["{$creator}"]\n')
    w("    kickoff: |\n")
    w("      @{team}-triage this is the employee help room. Introduce yourself to employees in two short lines.\n\n")
    w("links:\n")
    w('  - from: "security-help"\n')
    w('    to: "soc-shift"\n')
    w("    label: escalates to the SOC desk\n")
    return "".join(out)


def main(argv=None) -> int:
    p = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    p.add_argument("--check", action="store_true", help="Exit 1 if the template is out of date")
    args = p.parse_args(argv)
    text = build()
    if args.check:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            print("switch/soc-shift-relay.template.yaml is out of date: run python tools/build_template.py")
            return 1
        print("template is up to date")
        return 0
    with OUT.open("w", encoding="utf-8", newline="\n") as fh:  # write_text has no newline= before 3.10
        fh.write(text)
    print(f"wrote {OUT.relative_to(ROOT).as_posix()} ({len(text.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
